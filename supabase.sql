-- MS3DH NEXUS applications schema
-- Run this in Supabase SQL Editor.
create table if not exists public.application_settings (
  id integer primary key default 1 check (id = 1),
  is_open boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.application_settings (id, is_open)
values (1, false)
on conflict (id) do nothing;

create table if not exists public.application_questions (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(label) between 1 and 500),
  input_type text not null default 'long'
    check (input_type in ('text', 'number', 'long')),
  required boolean not null default true,
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  applicant_discord_id text,
  applicant_discord_name text not null,
  answers jsonb not null default '{}'::jsonb,
  status text not null default 'قيد المراجعة'
    check (status in ('قيد المراجعة', 'مقبول', 'مرفوض')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- RLS is enabled. The service role key is used only server-side by Netlify Functions.
alter table public.application_settings enable row level security;
alter table public.application_questions enable row level security;
alter table public.applications enable row level security;

-- No public policies are intentionally created. Do not expose the service role key to the browser.
